func TestGenericTreeRebalance(t *testing.T) {
	gimme := func(order, item_count int) *GenericTree[int, int] {
		tree, err := NewGenericTree[int, int](t.Name(), order)
		ensureError(t, err)

		values := rand.Perm(item_count)

		for _, v := range values {
			tree.Insert(v+1, v+1)
		}

		return tree
	}

	t.Run("when rebalance count is -1", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := -1
		tree := gimme(order, items)
		ensureError(t, tree.Rebalance(rebalance), "cannot rebalance")
	})

	t.Run("when rebalance count is 0", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := 0
		tree := gimme(order, items)
		ensureError(t, tree.Rebalance(rebalance), "cannot rebalance")
	})

	t.Run("when rebalance count is 1", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := 1
		tree := gimme(order, items)
		ensureError(t, tree.Rebalance(rebalance), "cannot rebalance")
	})

	t.Run("when rebalance count is 2", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := 2
		tree := gimme(order, items)

		ensureError(t, tree.Rebalance(rebalance))

		ensureStructure(t, tree.root,
			newInternal(
				newInternal(
					&leafNode[int, int]{
						Runts:  []int{1, 2},
						Values: []int{1, 2},
					},
					&leafNode[int, int]{
						Runts:  []int{3, 4},
						Values: []int{3, 4},
					},
				),
				newInternal(
					&leafNode[int, int]{
						Runts:  []int{5},
						Values: []int{5},
					},
				),
			),
		)
	})

	t.Run("when rebalance count is less than order", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := order - 1
		tree := gimme(order, items)

		ensureError(t, tree.Rebalance(rebalance))

		ensureStructure(t, tree.root,
			newInternal(
				&leafNode[int, int]{
					Runts:  []int{1, 2, 3},
					Values: []int{1, 2, 3},
				},
				&leafNode[int, int]{
					Runts:  []int{4, 5},
					Values: []int{4, 5},
				},
			),
		)
	})

	t.Run("when rebalance count is equal to order", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := order
		tree := gimme(order, items)

		ensureError(t, tree.Rebalance(rebalance))

		ensureStructure(t, tree.root,
			newInternal(
				&leafNode[int, int]{
					Runts:  []int{1, 2, 3, 4},
					Values: []int{1, 2, 3, 4},
				},
				&leafNode[int, int]{
					Runts:  []int{5},
					Values: []int{5},
				},
			),
		)
	})

	t.Run("when rebalance count is larger than order", func(t *testing.T) {
		const order = 4
		const items = 5
		rebalance := order + 1
		tree := gimme(order, items)
		ensureError(t, tree.Rebalance(rebalance), "cannot rebalance")
	})
}

